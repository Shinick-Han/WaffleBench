"""Parse + validate the Omnigent agent bundle with the installed Omnigent package.

Run with the Omnigent tool interpreter (launch.ps1 -Validate does this). The MCP
sidecars are generated by ``launch.ps1 -Setup``; without them the specialists have
no MCP allowlist and validation fails.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from omnigent.spec import parse, validate

EXPECTED_MODEL = "claude-opus-5-5"
EXPECTED_HARNESS = "claude-sdk"
EXPECTED_TOOLS = {
    "falsify_supervisor": set(),
    "experimenter": {"simulate_pvt_point", "read_result"},
    "analyst": {"analyze_and_plan", "read_result"},
}
EXPECTED_CAPS = {"falsify_supervisor": 12, "experimenter": 6, "analyst": 6}
EXPECTED_ROLE_ENV = {"experimenter": "experimenter", "analyst": "analyst"}


def _tool_cap(spec: object) -> int | None:
    guard = getattr(spec, "guardrails", None)
    policies = getattr(guard, "policies", None) or {}
    items = policies.values() if isinstance(policies, dict) else policies
    for pol in items:
        fn = getattr(pol, "function", None)
        path = getattr(fn, "path", None) if fn is not None else None
        if path and path.endswith("max_tool_calls_per_session"):
            return (getattr(fn, "arguments", None) or {}).get("limit")
    return None


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "agent").resolve()
    spec = parse(root)
    problems: list[str] = []
    report: dict[str, object] = {}
    specs = [spec, *spec.sub_agents]
    for s in specs:
        res = validate(s)
        problems += [f"{s.name}: {e}" for e in getattr(res, "errors", [])]
        ex = s.executor
        mcp = {m.name: sorted(m.tools or []) for m in s.mcp_servers}
        envs = {m.name: dict(getattr(m, "env", None) or {}) for m in s.mcp_servers}
        cap = _tool_cap(s)
        report[s.name] = {
            "valid": res.valid,
            "harness": ex.config.get("harness"),
            "model": ex.model,
            "reasoning_effort": ex.reasoning_effort,
            "skills": getattr(s, "skills", None) if isinstance(getattr(s, "skills", None), (str, type(None))) else "configured",
            "os_env": None if s.os_env is None else s.os_env.type,
            "mcp_allowlists": mcp,
            "mcp_roles": {k: v.get("FALSIFY_MCP_ROLE") for k, v in envs.items()},
            "tool_call_cap": cap,
        }
        if ex.model != EXPECTED_MODEL or ex.reasoning_effort != "medium":
            problems.append(f"{s.name}: model/effort is {ex.model}/{ex.reasoning_effort}")
        if ex.config.get("harness") != EXPECTED_HARNESS:
            problems.append(f"{s.name}: harness is {ex.config.get('harness')}")
        if s.os_env is not None:
            problems.append(f"{s.name}: os_env must be absent (no shell/filesystem tools)")
        if s.name not in EXPECTED_TOOLS:
            problems.append(f"unexpected agent {s.name}")
            continue
        got = {t for tools in mcp.values() for t in tools}
        if got != EXPECTED_TOOLS[s.name]:
            problems.append(f"{s.name}: MCP allowlist {sorted(got)} != {sorted(EXPECTED_TOOLS[s.name])}")
        if any(n.startswith("claude_ai") for n in mcp):
            problems.append(f"{s.name}: claude.ai connector present")
        role = EXPECTED_ROLE_ENV.get(s.name)
        if role and {v.get("FALSIFY_MCP_ROLE") for v in envs.values()} != {role}:
            problems.append(f"{s.name}: sidecar FALSIFY_MCP_ROLE must be {role!r}")
        if cap is not None and cap != EXPECTED_CAPS[s.name]:
            problems.append(f"{s.name}: tool-call cap {cap} != {EXPECTED_CAPS[s.name]}")
    if spec.name != "falsify_supervisor":
        problems.append(f"root agent is {spec.name}, expected falsify_supervisor")
    if sorted(a.name for a in spec.sub_agents) != ["analyst", "experimenter"]:
        problems.append("supervisor must have exactly the analyst and experimenter sub-agents")
    raw = {p.parent.name if p.parent != root else "falsify_supervisor": p.read_text(encoding="utf-8")
           for p in [root / "config.yaml", *sorted((root / "agents").glob("*/config.yaml"))]}
    for name, text in raw.items():
        # The parser's guardrail objects vary between Omnigent versions; check the declared caps textually too.
        if f"limit: {EXPECTED_CAPS.get(name)}" not in text or "skills: none" not in text:
            problems.append(f"{name}: config must keep skills: none and tool-call cap {EXPECTED_CAPS.get(name)}")
    print(json.dumps({"agents": report, "problems": problems}, indent=2, default=str))
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
